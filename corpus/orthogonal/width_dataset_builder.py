"""
corpus/orthogonal/width_dataset_builder.py — Width training dataset builder for
Orthogonal Calibration (Benda, 2026 §2.2).

A ``WidthDatasetBuilder`` takes a trajectory and a generation index ``n``, then
produces a JSONL training dataset containing *multiple architecturally diverse*
lateral solutions for the evolutionary jump aₙ₋₁ → aₙ.

Each solution is:
  1. Generated by the agent from the predecessor code aₙ₋₁ using diverse
     prompts (varied creativity temperature signals embedded in the prompt text).
  2. Annotated with objective static metrics derived from the existing
     ``extract_features`` utility (op-count proxy, parameter count, code length).
  3. Filtered so only solutions that remain within ``performance_tolerance`` of
     the historical aₙ metric baseline pass into the dataset.

The resulting JSONL is written to ``data/d_width/gen_{n}/width_gen_{n}.jsonl``
and uses the same ``{"prompt": ..., "completion": ...}`` schema as 𝒟_Gen so it
can be consumed by ``train.py`` without modification.

Usage
-----
    from corpus.orthogonal.width_dataset_builder import WidthDatasetBuilder
    from corpus.regression_pipeline.schemas import TrajectoryStep

    builder = WidthDatasetBuilder(cfg, agent)
    record = builder.build(
        before=trajectory_steps[n - 1],
        after=trajectory_steps[n],
        generation_index=n,
        output_dir=Path("data/d_width"),
    )
"""

from __future__ import annotations

import json
import logging
import re
import uuid
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

from corpus.regression_pipeline.schemas import TrajectoryStep

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Pydantic models
# ---------------------------------------------------------------------------


class LateralVariant(BaseModel):
    """One architecturally diverse lateral solution for a generational jump."""

    variant_id: str
    generation_index: int
    code: str
    rationale: str
    static_metrics: dict[str, float] = Field(default_factory=dict)
    performance_delta: float = Field(
        0.0,
        description=(
            "Fractional deviation of this variant's static metric proxy vs the "
            "historical aₙ baseline.  Values < performance_tolerance pass the filter."
        ),
    )
    passed_filter: bool = True
    prompt: str = ""
    completion: str = ""


class WidthDatasetRecord(BaseModel):
    """Output record produced by WidthDatasetBuilder for one generational jump."""

    generation_index: int
    before_algorithm_id: str
    after_algorithm_id: str
    variants_attempted: int
    variants_accepted: int
    output_path: str
    variant_ids: list[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Prompt templates
# ---------------------------------------------------------------------------

_WIDTH_SYSTEM = (
    "You are an elite ML researcher. "
    "Your goal is to design a NOVEL, ARCHITECTURALLY DIVERSE Python algorithm "
    "that achieves the same performance leap as the historical successor, but via a "
    "DIFFERENT structural approach. "
    "Do not simply replicate the historical solution — invent a creative alternative. "
    "Respond ONLY with a Python code block."
)

# Five prompt variants with different creativity-nudge phrasings to maximise
# architectural diversity across the lateral dataset.
_WIDTH_PROMPT_VARIANTS = [
    # Variant A — pure creativity
    """\
=== PREDECESSOR ALGORITHM (a_{before_idx}) ===
{before_code}

=== TARGET PERFORMANCE DELTA ===
ΔFitness: {delta_fitness:.4f}  (the historical successor achieved this improvement)

Design a NOVEL Python algorithm that achieves an equivalent performance gain via
a COMPLETELY DIFFERENT architectural approach than the obvious or historical solution.
Think laterally — consider sparse structures, alternative normalisation strategies,
factored representations, or any creative architectural choice.

```python
<novel code here>
```
""",
    # Variant B — explicit anti-memorisation nudge
    """\
=== PREDECESSOR ALGORITHM (a_{before_idx}) ===
{before_code}

=== TASK ===
The next evolutionary step achieves a fitness gain of {delta_fitness:.4f}.
IMPORTANT: Do NOT replicate the known historical successor.
Instead, propose an architecturally DISTINCT solution that achieves equivalent
or better performance through a different mechanism.

```python
<distinct code here>
```
""",
    # Variant C — constraint-based creativity
    """\
=== PREDECESSOR ALGORITHM (a_{before_idx}) ===
{before_code}

=== LATERAL DESIGN CHALLENGE ===
Target fitness gain: {delta_fitness:.4f}
Constraint: Your solution MUST differ structurally from the predecessor in at
least two of: layer types, normalisation, activation, regularisation, optimiser.

```python
<lateral solution here>
```
""",
    # Variant D — inversion framing
    """\
=== PREDECESSOR ALGORITHM (a_{before_idx}) ===
{before_code}

=== INVERSE DESIGN BRIEF ===
Rather than following the expected path of improvement (fitness delta={delta_fitness:.4f}),
identify an UNCONVENTIONAL structural transformation of the predecessor that achieves
the same outcome via a surprising architectural pivot.

```python
<unconventional code here>
```
""",
    # Variant E — free-form exploration
    """\
=== PREDECESSOR ALGORITHM (a_{before_idx}) ===
{before_code}

=== EXPLORATION BRIEF ===
Fitness target delta: {delta_fitness:.4f}
Freely explore the architectural design space.  Propose a Python algorithm that
improves upon the predecessor via a mechanism not typically used in this domain.

```python
<exploration code here>
```
""",
]


def _extract_code(text: str) -> str:
    """Extract the first Python fenced code block from an LLM response."""
    match = re.search(r"```python\s*(.*?)```", text, re.DOTALL)
    if match:
        return match.group(1).strip()
    return re.sub(r"```[a-z]*", "", text).strip()


def _extract_rationale(text: str) -> str:
    """Return any text outside the code block as a rationale."""
    cleaned = re.sub(r"```python.*?```", "", text, flags=re.DOTALL).strip()
    return cleaned or "No rationale provided."


# ---------------------------------------------------------------------------
# Performance proxy
# ---------------------------------------------------------------------------


def _compute_static_metrics(code: str) -> dict[str, float]:
    """
    Compute lightweight static structural metrics for performance comparison.

    Uses the existing ``extract_features`` AST extractor.  Returns a dict
    with the subset of features most relevant to performance estimation:
    code length, function count, class count, call count, and nesting depth.
    These serve as a GPU-free proxy for FLOPs / memory.
    """
    try:
        from corpus.performance_estimator.feature_extractor import extract_features
        features = extract_features(code)
        return {
            "code_length_chars": features.get("code_length_chars", 0.0),
            "num_functions": features.get("num_functions", 0.0),
            "num_classes": features.get("num_classes", 0.0),
            "num_calls": features.get("num_calls", 0.0),
            "max_nesting_depth": features.get("max_nesting_depth", 0.0),
            "num_loops": features.get("num_loops", 0.0),
            "log_code_chars": features.get("log_code_chars", 0.0),
        }
    except Exception as exc:
        logger.debug("Static metric extraction failed: %s", exc)
        return {
            "code_length_chars": float(len(code)),
            "num_functions": 0.0,
            "num_classes": 0.0,
            "num_calls": 0.0,
            "max_nesting_depth": 0.0,
            "num_loops": 0.0,
            "log_code_chars": 0.0,
        }


def _performance_delta(
    variant_metrics: dict[str, float],
    baseline_metrics: dict[str, float],
) -> float:
    """
    Compute a scalar performance delta between a variant and the historical baseline.

    Returns the mean absolute fractional deviation across all shared metrics
    (excluding zero-valued baseline keys to avoid division by zero).
    A value of 0.0 means the variant is structurally identical to the baseline;
    a value of 1.0 means it is completely different in every metric dimension.
    """
    shared = [
        k for k in variant_metrics
        if k in baseline_metrics and baseline_metrics[k] != 0.0
    ]
    if not shared:
        return 0.0
    deltas = [
        abs(variant_metrics[k] - baseline_metrics[k]) / abs(baseline_metrics[k])
        for k in shared
    ]
    return sum(deltas) / len(deltas)


# ---------------------------------------------------------------------------
# WidthDatasetBuilder
# ---------------------------------------------------------------------------


class WidthDatasetBuilder:
    """
    Builds the Width training dataset for one generational jump aₙ₋₁ → aₙ.

    Parameters
    ----------
    cfg:
        Full runtime config dict.
    agent:
        An initialised ``AgentClient`` used to generate lateral variants.
    """

    def __init__(self, cfg: dict | None = None, agent: Any = None) -> None:
        self._cfg = cfg or {}
        oc_cfg = self._cfg.get("orthogonal_calibration", {})
        width_cfg = oc_cfg.get("width", {})

        self._lateral_variants: int = int(width_cfg.get("lateral_variants_per_jump", 4))
        self._performance_tolerance: float = float(
            width_cfg.get("performance_tolerance", 0.05)
        )
        self._max_code_chars: int = int(
            self._cfg.get("calibration", {}).get("max_code_chars", 8000)
        )

        if agent is None:
            from etft.agent import AgentClient
            self._agent = AgentClient(self._cfg)
        else:
            self._agent = agent

    # ------------------------------------------------------------------
    def build(
        self,
        before: TrajectoryStep,
        after: TrajectoryStep,
        generation_index: int,
        output_dir: Path,
    ) -> WidthDatasetRecord:
        """
        Generate lateral Width training examples for the jump *before* → *after*.

        Parameters
        ----------
        before:
            The predecessor algorithm (aₙ₋₁).
        after:
            The historical successor (aₙ) — used as performance baseline.
        generation_index:
            Integer index ``n`` (used for output directory naming).
        output_dir:
            Root directory under which ``gen_{n}/`` is created.

        Returns
        -------
        WidthDatasetRecord
            Summary of the build run.
        """
        gen_dir = output_dir / f"gen_{generation_index}"
        gen_dir.mkdir(parents=True, exist_ok=True)
        out_path = gen_dir / f"width_gen_{generation_index}.jsonl"

        logger.info(
            "WidthDatasetBuilder: building gen_%d dataset "
            "(%d variants requested, tolerance=%.3f) …",
            generation_index, self._lateral_variants, self._performance_tolerance,
        )

        # Compute baseline static metrics from the historical successor aₙ
        baseline_metrics = _compute_static_metrics(after.code)
        delta_fitness = after.fitness_score - before.fitness_score

        before_code = before.code[:self._max_code_chars]

        variants_accepted: list[LateralVariant] = []
        variant_ids: list[str] = []

        for i in range(self._lateral_variants):
            variant = self._generate_variant(
                before_code=before_code,
                before_idx=before.step_index,
                delta_fitness=delta_fitness,
                generation_index=generation_index,
                prompt_variant_index=i % len(_WIDTH_PROMPT_VARIANTS),
                baseline_metrics=baseline_metrics,
            )
            if variant is None:
                continue

            if variant.passed_filter:
                variants_accepted.append(variant)
                variant_ids.append(variant.variant_id)
                logger.info(
                    "WidthDatasetBuilder: variant %s accepted "
                    "(perf_delta=%.4f ≤ tolerance=%.4f)",
                    variant.variant_id, variant.performance_delta,
                    self._performance_tolerance,
                )
            else:
                logger.debug(
                    "WidthDatasetBuilder: variant %s rejected "
                    "(perf_delta=%.4f > tolerance=%.4f)",
                    variant.variant_id, variant.performance_delta,
                    self._performance_tolerance,
                )

        # Write accepted variants to JSONL
        with open(out_path, "w") as fh:
            for variant in variants_accepted:
                record = {"prompt": variant.prompt, "completion": variant.completion}
                fh.write(json.dumps(record) + "\n")

        logger.info(
            "WidthDatasetBuilder: gen_%d done — %d / %d variants accepted → %s",
            generation_index, len(variants_accepted), self._lateral_variants, out_path,
        )

        return WidthDatasetRecord(
            generation_index=generation_index,
            before_algorithm_id=before.algorithm_id,
            after_algorithm_id=after.algorithm_id,
            variants_attempted=self._lateral_variants,
            variants_accepted=len(variants_accepted),
            output_path=str(out_path),
            variant_ids=variant_ids,
        )

    # ------------------------------------------------------------------
    def _generate_variant(
        self,
        before_code: str,
        before_idx: int,
        delta_fitness: float,
        generation_index: int,
        prompt_variant_index: int,
        baseline_metrics: dict[str, float],
    ) -> LateralVariant | None:
        """Generate one lateral variant and evaluate it against the performance filter."""
        prompt_template = _WIDTH_PROMPT_VARIANTS[prompt_variant_index]
        prompt = prompt_template.format(
            before_idx=before_idx,
            before_code=before_code,
            delta_fitness=delta_fitness,
        )

        agent_result = self._agent.run_task(task=prompt, system=_WIDTH_SYSTEM)
        if not agent_result.success:
            logger.warning(
                "WidthDatasetBuilder: agent call failed for gen_%d variant %d.",
                generation_index, prompt_variant_index,
            )
            return None

        code = _extract_code(agent_result.output)
        if not code:
            logger.debug(
                "WidthDatasetBuilder: no code block in agent output for gen_%d variant %d.",
                generation_index, prompt_variant_index,
            )
            return None

        rationale = _extract_rationale(agent_result.output)
        variant_metrics = _compute_static_metrics(code)
        perf_delta = _performance_delta(variant_metrics, baseline_metrics)
        passed = perf_delta <= self._performance_tolerance

        # Build the training example (same schema as 𝒟_Gen)
        training_prompt = (
            f"# Orthogonal Width Training — Generation {generation_index}\n"
            f"# Task: Given the predecessor algorithm below, propose a NOVEL, "
            f"architecturally diverse successor that achieves fitness gain "
            f"{delta_fitness:.4f}.\n\n"
            f"{before_code}"
        )

        return LateralVariant(
            variant_id=str(uuid.uuid4())[:8],
            generation_index=generation_index,
            code=code,
            rationale=rationale,
            static_metrics=variant_metrics,
            performance_delta=perf_delta,
            passed_filter=passed,
            prompt=training_prompt,
            completion=code,
        )
