from pydantic import BaseModel, Field


class ProvenanceMetadata(BaseModel):
    """Metadata to track the origin of context to avoid blind hallucinations."""
    source_file: str = Field(description="The source file from which the data was extracted.")
    version: str = Field(description="Version of the extracted data or document.")
    revision_id: str = Field(description="Revision identifier (e.g., git commit hash).")
    truncated: bool = Field(default=False, description="Whether the context was truncated due to token limits.")

class Task(BaseModel):
    """A smaller, independent technical task derived from a larger requirement."""
    title: str
    description: str

class ImplementationPath(BaseModel):
    """A proposed path for implementation with specific trade-offs."""
    name: str
    description: str
    tradeoffs: str

class BusinessAnalysisDocument(BaseModel):
    """The structured output of the Business Analyst Agent."""
    intent: str = Field(description="The core intent and goal of the requirement.")
    requirements: list[str] = Field(description="List of specific functional and non-functional requirements.")
    implementation_paths: list[ImplementationPath] = Field(description="Three proposed implementation paths (e.g., Quick Win, Standard, Overhaul).")
    selected_path: str | None = Field(default=None, description="The path selected by the user/stakeholder.")
    provenance: ProvenanceMetadata | None = Field(default=None, description="Data provenance tracking.")

class DataStructure(BaseModel):
    """Proposed data structure for the architecture."""
    name: str
    description: str
    fields: dict[str, str]

class APIContract(BaseModel):
    """Defined API interface contract."""
    endpoint: str
    method: str
    request_schema: str
    response_schema: str

class ArchitectureDecisionRecord(BaseModel):
    """The formal architecture design generated by the System Architect Agent."""
    data_structures: list[DataStructure] = Field(description="List of required data models/structures.")
    api_contracts: list[APIContract] = Field(description="List of API contracts and interfaces.")
    dependencies: list[str] = Field(description="List of required software dependencies.")
    tasks: list[Task] = Field(description="Decomposed technical tasks ready for execution.")
    provenance: ProvenanceMetadata | None = Field(default=None, description="Data provenance tracking.")
